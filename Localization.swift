import Foundation

/// Only app-owned display strings use this catalog. Stable model/persistence values
/// and user content (names, paths, clipboard text) remain in their original form.
enum L10n {
    static let changed = Notification.Name("ailock.languageChanged")

    static func usesEnglish(defaults: UserDefaults = .standard, preferredLanguages: [String] = Locale.preferredLanguages) -> Bool {
        let followsSystem = defaults.object(forKey: "overview.followSystemLanguage") as? Bool ?? true
        if followsSystem { return !(preferredLanguages.first?.lowercased().hasPrefix("zh") ?? false) }
        return defaults.bool(forKey: "overview.language")
    }
    static var isEnglish: Bool { usesEnglish() }

    static func text(_ source: String) -> String { translate(source, english: isEnglish) }

    static func translate(_ source: String, english: Bool) -> String {
        if source == "DockLock" { return english ? "DockLock" : "锁定程序坞" }
        guard english, !source.isEmpty else { return source }
        if let exact = catalog[source] { return exact }
        let hasChinese = source.unicodeScalars.contains { (0x4E00...0x9FFF).contains($0.value) }
        return render(source, rules: hasChinese ? rules : nonChineseRules) ?? source
    }

    /// Compound status labels are app-owned; their components remain stable in models.
    static func statusList(_ source: String) -> String {
        let complete = text(source)
        if complete != source { return complete }
        return source.components(separatedBy: " · ").map(text).joined(separator: " · ")
    }

    static func format(_ template: String, arguments: [String]) -> String {
        let translated = isEnglish ? catalog[template] ?? template : template
        let result = NSMutableString(string: translated)
        let slots = try! NSRegularExpression(pattern: #"%\{([0-9]+)\}"#)
        for slot in slots.matches(in: translated, range: NSRange(location: 0, length: (translated as NSString).length)).reversed() {
            let index = Int((translated as NSString).substring(with: slot.range(at: 1)))!
            if arguments.indices.contains(index) { result.replaceCharacters(in: slot.range, with: arguments[index]) }
        }
        return result as String
    }

    /// Recover app-owned native control text when changing back to Chinese.
    static func original(_ displayed: String) -> String {
        if let exact = reverseCatalog[displayed] { return exact }
        return render(displayed, rules: reverseRules) ?? displayed
    }

    private struct Rule {
        let expression: NSRegularExpression
        let target: String
        let slots: [String]
    }
    private static func makeRules(_ pairs: [(String, String)]) -> [Rule] {
        let slotPattern = try! NSRegularExpression(pattern: #"%\{[0-9]+\}"#)
        return pairs.filter { $0.0.contains("%{") }
            .sorted { $0.0.count > $1.0.count }
            .compactMap { source, target in
                let nsSource = source as NSString
                let matches = slotPattern.matches(in: source, range: NSRange(location: 0, length: nsSource.length))
                var pattern = "\\A", offset = 0
                var slots: [String] = []
                for match in matches {
                    pattern += NSRegularExpression.escapedPattern(for: nsSource.substring(with: NSRange(location: offset, length: match.range.location - offset)))
                    pattern += "([\\s\\S]*?)"
                    slots.append(nsSource.substring(with: match.range))
                    offset = NSMaxRange(match.range)
                }
                pattern += NSRegularExpression.escapedPattern(for: nsSource.substring(from: offset)) + "\\z"
                guard let expression = try? NSRegularExpression(pattern: pattern) else { return nil }
                return Rule(expression: expression, target: target, slots: slots)
            }
    }
    private static func render(_ source: String, rules: [Rule]) -> String? {
        let value = source as NSString
        let range = NSRange(location: 0, length: value.length)
        for rule in rules {
            guard let match = rule.expression.firstMatch(in: source, range: range) else { continue }
            let arguments = Dictionary(zip(rule.slots, (1..<match.numberOfRanges).map { value.substring(with: match.range(at: $0)) }), uniquingKeysWith: { first, _ in first })
            // Substitute once: an argument containing "%{0}" is user content, not a new slot.
            let slotPattern = try! NSRegularExpression(pattern: #"%\{[0-9]+\}"#)
            let result = NSMutableString(string: rule.target)
            for slot in slotPattern.matches(in: rule.target, range: NSRange(location: 0, length: (rule.target as NSString).length)).reversed() {
                let key = (rule.target as NSString).substring(with: slot.range)
                result.replaceCharacters(in: slot.range, with: arguments[key] ?? key)
            }
            return result as String
        }
        return nil
    }
    private static let reverseCatalog = Dictionary(catalog.sorted { $0.key < $1.key }.filter { !$0.key.contains("%{") }.map { ($0.value, $0.key) }, uniquingKeysWith: { first, _ in first })
    private static let rules = makeRules(catalog.map { ($0.key, $0.value) })
    private static let nonChineseRules = makeRules(catalog.filter {
        !$0.key.unicodeScalars.contains { (0x4E00...0x9FFF).contains($0.value) }
    }.map { ($0.key, $0.value) })
    private static let reverseRules = makeRules(catalog.map { ($0.value, $0.key) })

